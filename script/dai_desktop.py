#!/usr/bin/env python3
"""Opt-in D_AI OS adapter installer for the OpenCode V2 Desktop fork.

Copies only D_AI-owned files into a user-selected OpenCode configuration tree.
No user config is parsed or replaced; the MCP connection is registered with a
V2 plugin transform. A manifest guards updates/removal against user edits.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys
import venv

MANIFEST = '.dai-desktop-manifest.json'
SOURCE_URL = 'https://github.com/amroquqa99-art/D_AI'


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def runtime_default() -> Path:
    home = Path.home() / '.local' / 'share' / 'd-ai' / 'runtime'
    return home / ('Scripts/python.exe' if os.name == 'nt' else 'bin/python')


def collect(source: Path, python: Path) -> dict[str, bytes]:
    adapter = source / 'adapters' / 'opencode'
    for group in ('agent', 'skill', 'command'):
        if not (adapter / group).is_dir():
            raise ValueError(f'Missing D_AI adapter directory: {adapter / group}')
    if not (adapter / 'skill/dai-core/SKILL.md').is_file():
        raise ValueError('D_AI adaptive-workflow-os core skill is missing')
    files: dict[str, bytes] = {}
    for group, plural in (('agent', 'agents'), ('skill', 'skills'), ('command', 'commands')):
        for item in sorted((adapter / group).rglob('*')):
            if not item.is_file() or item.is_symlink():
                continue
            relative = item.relative_to(adapter / group)
            if group == 'command':
                relative = relative.with_name(f'dai-{relative.name}')
            target = Path(plural) / relative
            if target.as_posix() in files:
                raise ValueError(f'Duplicate adapter destination: {target}')
            files[target.as_posix()] = item.read_bytes()
    # Selectable primary: it never overwrites the user's chosen model.
    files['agents/dai-os.md'] = b'''---
description: D_AI OS adaptive orchestration (D_AI source adapter)
mode: primary
---

You are the D_AI OS entry point. For substantive tasks load the `dai-core` skill and its relevant reference files, then activate only applicable D_AI domain skills/agents. Use D_AI MCP tools only if the `dai` server is actually connected. Apply SNAP/STANDARD/DEEP/CRITICAL, explicit acceptance criteria, typed evidence claims and independent verification. Never invent mission state, evidence, model access, successful tool calls or cost. Do not select or switch to paid models without owner authorization. Preserve the host's permission boundaries; ask when authorization is required. If the core is unavailable, report it instead of acting as if D_AI is active.
'''
    # OpenCode V2 MCP transform avoids replacing user JSON/JSONC.
    executable = json.dumps(str(python.resolve()))
    root = json.dumps(str(source.resolve()))
    plugin = f'''// Generated by script/dai_desktop.py. Re-run install to refresh.
// D_AI source: {SOURCE_URL}
export default {{
  id: "dai.desktop.mcp",
  async setup(ctx) {{
    const registration = await ctx.mcp.transform((editor) => {{
      if (editor.get("dai")) return; // Owner config wins.
      editor.set("dai", {{
        type: "local", command: [{executable}, "-m", "dai.mcp_server"],
        environment: {{ DAI_PROJECT_ROOT: {root} }}
      }});
    }});
    return () => registration.dispose();
  }}
}};
'''
    files['plugins/dai-desktop-mcp.js'] = plugin.encode('utf-8')
    return files


def manifest_at(target: Path) -> Path:
    return target / MANIFEST


def load_manifest(target: Path) -> dict:
    path = manifest_at(target)
    if not path.exists():
        return {'version': 1, 'files': {}}
    data = json.loads(path.read_text('utf-8'))
    if data.get('version') != 1 or not isinstance(data.get('files'), dict):
        raise ValueError('Unknown D_AI manifest schema; refusing to mutate files')
    return data


def checked_file(target: Path, name: str) -> Path:
    rel = Path(name)
    if rel.is_absolute() or '..' in rel.parts:
        raise ValueError('Invalid path in D_AI manifest')
    path = target / rel
    if not path.resolve().is_relative_to(target.resolve()):
        raise ValueError('D_AI destination escapes target through a symlink')
    return path


def write_atomic(path: Path, content: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_name(path.name + '.dai-tmp')
    if temp.exists():
        raise FileExistsError(f'Temporary file exists: {temp}')
    with temp.open('xb') as out:
        out.write(content)
    os.replace(temp, path)


def install(source: Path, target: Path, python: Path) -> dict:
    source = source.resolve()
    target = target.resolve()
    payload = collect(source, python)
    before = load_manifest(target)
    owned: dict[str, str] = before['files']
    if before.get('source') and before['source'] != str(source):
        raise ValueError('Manifest is owned by a different D_AI source; uninstall first')
    # No writes unless every destination is proven unchanged.
    for name in set(payload) | set(owned):
        path = checked_file(target, name)
        if path.is_symlink():
            raise FileExistsError(f'Refusing to overwrite symlink: {path}')
        if path.exists():
            if not path.is_file() or name not in owned or digest(path.read_bytes()) != owned[name]:
                raise FileExistsError(f'Not owned or user-edited: {path}')
    changed = []
    for name, content in payload.items():
        path = checked_file(target, name)
        if not path.exists() or path.read_bytes() != content:
            write_atomic(path, content)
            changed.append(name)
    removed = []
    for name in owned.keys() - payload.keys():
        checked_file(target, name).unlink(missing_ok=True)
        removed.append(name)
    new_manifest = {'version': 1, 'source': str(source), 'python': str(python.resolve()),
                    'files': {name: digest(content) for name, content in payload.items()}}
    write_atomic(manifest_at(target), (json.dumps(new_manifest, indent=2, sort_keys=True) + '\n').encode())
    return {'status': 'installed', 'definitions': len(payload), 'updated': len(changed),
            'removed': len(removed), 'target': str(target), 'mcp': 'configured-not-verified'}


def status(target: Path) -> dict:
    data = load_manifest(target)
    missing, altered = [], []
    for name, sha in data['files'].items():
        path = checked_file(target, name)
        if not path.is_file() or path.is_symlink():
            missing.append(name)
        elif digest(path.read_bytes()) != sha:
            altered.append(name)
    return {'status': 'ok' if data['files'] and not missing and not altered else 'incomplete',
            'tracked': len(data['files']), 'missing': missing, 'altered': altered,
            'mcp': 'not-probed'}


def remove(target: Path) -> dict:
    data = load_manifest(target)
    kept, removed = [], []
    for name, sha in data['files'].items():
        path = checked_file(target, name)
        if not path.exists():
            continue
        if path.is_symlink() or not path.is_file() or digest(path.read_bytes()) != sha:
            kept.append(name)
            continue
        path.unlink()
        removed.append(name)
    if kept:
        data['files'] = {key: data['files'][key] for key in kept}
        write_atomic(manifest_at(target), (json.dumps(data, indent=2) + '\n').encode())
    else:
        manifest_at(target).unlink(missing_ok=True)
    return {'removed': len(removed), 'kept_user_edits': kept}


def bootstrap(source: Path, python: Path) -> None:
    if not python.is_file():
        venv.EnvBuilder(with_pip=True).create(python.parent.parent)
    subprocess.run([str(python), '-m', 'pip', 'install', '-e', f'{source.resolve()}[mcp]'], check=True)


def main() -> int:
    p = argparse.ArgumentParser(description='Install D_AI OS into OpenCode V2 Desktop')
    p.add_argument('action', choices=('install', 'status', 'remove'))
    p.add_argument('--source', type=Path, help='local clone of the D_AI repository')
    p.add_argument('--target', type=Path, default=Path.home() / '.config' / 'opencode')
    p.add_argument('--python', type=Path, default=runtime_default())
    p.add_argument('--bootstrap', action='store_true', help='install D_AI runtime in isolated venv')
    args = p.parse_args()
    try:
        if args.action == 'status':
            report = status(args.target)
        elif args.action == 'remove':
            report = remove(args.target)
        else:
            if args.source is None:
                p.error('install requires --source pointing to a local D_AI clone')
            if args.bootstrap:
                bootstrap(args.source, args.python)
            if not args.python.is_file():
                raise FileNotFoundError('Runtime missing: use --bootstrap or --python')
            # Import probe checks Python dependency availability, not a live MCP handshake.
            subprocess.run([str(args.python), '-c', 'import dai.mcp_server'],
                           check=True, stdout=subprocess.DEVNULL, timeout=30)
            report = install(args.source, args.target, args.python)
        print(json.dumps(report, ensure_ascii=False, indent=2))
        return 0 if report.get('status') != 'incomplete' else 2
    except (OSError, ValueError, subprocess.SubprocessError) as exc:
        print(json.dumps({'status': 'error', 'reason': str(exc)}), file=sys.stderr)
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
